// Builds app/madaya.css from the Madaya centre's own stylesheet (app/globals.css on oz819/madaya
// main), unchanged, but scoped to :root[data-ui-theme="madaya"] so it is the look inside the app
// (the default of «المظهر») and nothing else. Run: node scripts/build-madaya-css.mjs <madaya globals.css>
import { readFileSync, writeFileSync } from "node:fs";
import postcss from "postcss";

const S = ':root[data-ui-theme="madaya"]';
const src = readFileSync(process.argv[2], "utf8");
const root = postcss.parse(src);

function scope(sel) {
  return sel
    .split(",")
    .map((s) => s.trim())
    .map((s) => {
      if (s === ":root" || s === "html") return S;
      if (s === "body") return `${S} body`;
      if (s.startsWith("html ")) return `${S} ${s.slice(5)}`;
      if (s.startsWith(":root ")) return `${S} ${s.slice(6)}`;
      return `${S} ${s}`;
    })
    .join(",");
}

root.walk((node) => {
  if (node.type === "atrule" && (node.name === "keyframes" || node.name === "page" || node.name === "font-face")) {
    node.remove(); // the app already has these (same names); @page cert stays in globals.css
    return;
  }
  if (node.type === "rule" && !(node.parent?.type === "atrule" && /keyframes$/.test(node.parent.name))) {
    node.selector = scope(node.selector);
  }
});

const head = `/* GENERATED by scripts/build-madaya-css.mjs from the Madaya centre's app/globals.css — do not edit.
   The look inside the app exactly as in مركز تحفيظ مضايا; «المظهر» → «مضايا» (the default). */
${S} { color-scheme: light; }
${S} {
  /* names the newer parts of the app use, mapped onto Madaya's own colours */
  --accent: var(--g) !important; --accent-strong: var(--g2) !important; --accent-soft: #e8f3ee !important;
  --accent-2: var(--gold) !important; --accent-2-soft: #f8f0dc !important; --on-accent: #fff !important;
  --surface: #fff; --surface-2: #eef4f0; --line-strong: #cbd9d2; --danger: var(--red); --danger-soft: #fbeceb;
}
`;
// What app/theme.css sets explicitly where Madaya's sheet relies on inheritance, and the parts of
// the app Madaya never had («المظهر», «الرئيسية»), drawn in Madaya's colours.
const tail = `
${S} .app-bg > header h1,${S} .app-bg > header .dates,${S} .app-bg > header .userbox,${S} .app-bg > header .userbox > span{color:#fff}
${S} .app-bg > header .dates{align-items:center}
${S} .app-bg > header .userbox > span{opacity:.9}
${S} .app-bg > header .userbox button,${S} .app-bg > header .userbox .btn{background:#ffffff20;color:#fff;border:0}
${S} .app-bg > header .userbox button:hover{background:#ffffff35}
${S} .appearance-pop{background:#fff;color:var(--text);border:1px solid var(--line)}
${S} .app-bg > header .userbox .ap-swatch{padding:0;border:2px solid #cbd9d2}
${S} .app-bg > header .userbox .ap-swatch.on{border-color:var(--g)}
${S} .app-bg > header .userbox .ap-chip{background:#eef4f0;color:var(--text);border:1px solid var(--line);padding:6px 4px}
${S} .app-bg > header .userbox .ap-chip:hover{background:#e3ece7}
${S} .app-bg > header .userbox .ap-chip.on{background:#e8f3ee;border:1px solid var(--g);color:var(--g2)}
`;
writeFileSync(process.argv[3] || "app/madaya.css", head + root.toString() + "\n" + tail);
console.log("rules:", root.nodes.length);
